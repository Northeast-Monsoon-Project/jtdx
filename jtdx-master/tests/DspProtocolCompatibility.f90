! WSJT-X 3.0.2 protocol vectors, independently generated by its unmodified
! standard pack77 (commit ccdfaf3c1c109010d15399674ce278167cfde848).
program test_dsp_protocol_compatibility
  use packjt77, only: pack77,unpack77,ihashcall
  implicit none
  character(37),parameter :: messages(8)=[character(37):: &
    'CQ K1ABC FN20','K1ABC W9XYZ R-09','K1ABC W9XYZ 2A NB', &
    'K1ABC W9XYZ 2A GH','K1ABC W9XYZ 2A NS','K1ABC W9XYZ 2A TER', &
    'TU; W9XYZ K1ABC R 579 X99','TU; W9XYZ K1ABC R 579 DR']
  character(77),parameter :: vectors(8)=[character(77):: &
    '00000000000000000000000000100000010011011110111100011010100010100001010000001', &
    '00001001101111011110001101010000011000010100100111011100001111111010101010001', &
    '00001001101111011110001101010000110000101001001110111000000010001010110011000', &
    '00001001101111011110001101010000110000101001001110111000000010000010000011000', &
    '00001001101111011110001101010000110000101001001110111000000010000011001011000', &
    '00001001101111011110001101010000110000101001001110111000000010000101100011000', &
    '10000110000101001001110111000000010011011110111100011010111011111111101011011', &
    '10000110000101001001110111000000010011011110111100011010111011111110000010011']
  character(37) message,decoded
  character(77) bits
  character(13),parameter :: calls(6)=[character(13)::'K1ABC','BD4XNS/QRP','PJ4/K1ABC','ZZ9ZZZ','9A1A','ABCDEFGHIJK']
  ! Python arbitrary-precision (47055833459 * base38(call)) mod 2**64,
  ! followed by extraction of the most significant 10/12/22 bits.
  integer,parameter :: hashes(3,6)=reshape([712,2851,2920267,608,2433,2491474,346,1387,1420834, &
    121,487,499076,466,1864,1909282,525,2101,2152258],[3,6])
  integer,parameter :: widths(3)=[10,12,22]
  integer i,j,i3,n3
  logical ok
  do i=1,size(messages)
    message=messages(i);i3=-1;n3=-1
    call pack77(message,i3,n3,bits,1)
    if(bits.ne.vectors(i))then
      print *, 'Protocol differs from WSJT-X 3.0.2: ',messages(i)
      error stop 1
    endif
    call unpack77(bits,0,decoded,ok,1)
    if(.not.ok.or.decoded.ne.messages(i))error stop 'Protocol round-trip failed'
  enddo
  do i=1,size(calls)
    do j=1,size(widths)
      if(ihashcall(calls(i),widths(j)).ne.hashes(j,i))error stop 'Portable callsign hash mismatch'
    enddo
  enddo
  print *, 'WSJT-X 3.0.2 protocol compatibility PASS'
end program
